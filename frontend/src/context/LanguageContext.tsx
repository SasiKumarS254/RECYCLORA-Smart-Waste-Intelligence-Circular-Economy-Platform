const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<Language>('en');

  const t = (key: string, fallback?: string): string => {
    if (!key) return '';
    const currentDict = translations[language];
    if (currentDict && currentDict[key]) return currentDict[key];

    // Case-insensitive direct lookup or English phrase reverse lookup
    const enDict = translations['en'];
    if (enDict && currentDict) {
      const lowerKey = key.trim().toLowerCase();
      for (const [k, v] of Object.entries(enDict)) {
        if (v.trim().toLowerCase() === lowerKey && currentDict[k]) {
          return currentDict[k];
        }
      }
    }

    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
};
